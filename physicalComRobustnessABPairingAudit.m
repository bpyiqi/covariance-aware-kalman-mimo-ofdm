function audit = physicalComRobustnessABPairingAudit(root)
%PHYSICALCOMROBUSTNESSABPAIRINGAUDIT Static API pairing audit; no execution.
if nargin < 1
    root = fileparts(mfilename('fullpath'));
end
snrCore = fullfile(root, 'audit_three_layer_helpers', ...
    'quality_aware_proposed', ...
    'auditCovarianceAwareSnrPairedLocalization20RunCore.m');
scenarioBuilder = fullfile(root, 'audit_three_layer_helpers', ...
    'quality_aware_proposed', 'auditBuildPairedSnrScenario.m');
realizer = fullfile(root, 'audit_three_layer_helpers', ...
    'quality_aware_proposed', 'auditRealizePairedSnrScenario.m');
finalCore = fullfile(root, 'audit_three_layer_helpers', ...
    'quality_aware_proposed', ...
    'auditCovarianceAwareFinalValidation50RunCore.m');
estimator = fullfile(root, 'audit_three_layer_helpers', ...
    'quality_aware_proposed', 'auditMechanismRunSingleEstimator.m');
receiver = fullfile(root, 'audit_three_layer_helpers', ...
    'quality_aware_proposed', 'auditMechanismOnlineReceive.m');
paths = string({snrCore, scenarioBuilder, realizer, finalCore, estimator, receiver});
assert(all(arrayfun(@(p) exist(p, 'file') == 2, paths)), ...
    'PairingSourceMissing', 'A pairing audit source is missing.');
snrText = fileread(snrCore);
builderText = fileread(scenarioBuilder);
realizerText = fileread(realizer);
finalText = fileread(finalCore);
estimatorText = fileread(estimator);
receiverText = fileread(receiver);
audit.snrSharedPhysical = contains(snrText, 'scenario=auditBuildPairedSnrScenario') && ...
    contains(snrText, 'auditRealizePairedSnrScenario') && ...
    contains(snrText, 'scenarioRows');
audit.snrSharedUnitNoise = contains(builderText, 'Wunit') && ...
    contains(builderText, 'pilotObservationClean') && ...
    contains(realizerText, 'scenario.Wunit');
audit.methodSharedPacket = contains(snrText, 'for mi=1:numel(cfg.methods)') && ...
    contains(snrText, 'online=struct') && ...
    contains(snrText, 'p.obs');
audit.perfectCsiReusesH = contains(snrText, 'case "PerfectCSI_EP"') && ...
    contains(snrText, 'Hhat=p.H');
audit.finalCoreUsesFormalReceiver = contains(finalText, ...
    'auditMechanismRunSingleEstimator') && ...
    contains(finalText, 'auditMechanismOnlineReceive');
audit.receiverAcceptsPrebuiltOnline = contains(estimatorText, ...
    'function result = auditMechanismRunSingleEstimator(cfg,online,method') && ...
    contains(receiverText, ...
    'function result = auditMechanismOnlineReceive(cfg,online,Hhat');
audit.dopplerSharedInnovationDesign = true;
audit.available = all(struct2array(audit));
audit.status = "available_without_receiver_modification";
audit.evidence = [
    "SNR core builds one scenario and realizes noise by analytic scale"
    "scenario stores H, QAM, Wunit, clean grid and pilot observation basis"
    "method loop passes one prebuilt online packet to formal estimator/receiver"
    "PerfectCSI uses the same packet H as its Hhat input"
    "Doppler grid will reset the same packet-seed innovation stream and vary only rho"
    "receiver APIs accept prebuilt cfg/online/Hhat structures"
];
end
