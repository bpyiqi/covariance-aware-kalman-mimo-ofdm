function audit = auditVerifyFrozenPacketHashes(packet,packetIndex,conditionSeed,packetSeed,frozenTable,absoluteTolerance)
%AUDITVERIFYFROZENPACKETHASHES Exact seeds and CSV-aware absolute hash gate.
rows=frozenTable(frozenTable.payloadSymbols==packet.Npayload&frozenTable.packetIndex==packetIndex,:);
assert(~isempty(rows),'Frozen pairing row is missing: payloadSymbols=%d packetIndex=%d.',packet.Npayload,packetIndex);
expected=rows(1,:);assert(expected.conditionSeed==conditionSeed&&expected.packetSeed==packetSeed, ...
    'Frozen seed mismatch: payloadSymbols=%d packetIndex=%d.',packet.Npayload,packetIndex);
names={'informationBitsHash','transmitBitsHash','codedBitsHash','qamSymbolsHash','paddingMaskHash', ...
    'channelHash','noiseHash','receivedSignalHash','pilotObservationHash'};
difference=zeros(1,numel(names));exact=false(1,numel(names));
for index=1:numel(names)
    actual=packet.hashes.(names{index});reference=expected.(names{index});
    assert(isscalar(actual)&&isscalar(reference)&&isfinite(actual)&&isfinite(reference), ...
        'Nonfinite packet hash in %s.',names{index});
    exact(index)=actual==reference;difference(index)=abs(actual-reference);
    assert(exact(index)||difference(index)<=absoluteTolerance, ...
        'Frozen packet hash mismatch in %s: absDiff=%.17g exceeds absoluteTolerance=%.17g.', ...
        names{index},difference(index),absoluteTolerance);
end
audit=struct('maximumAbsoluteDifference',max(difference),'exactMatchCount',nnz(exact), ...
    'absoluteToleranceMatchCount',nnz(~exact),'fieldCount',numel(names), ...
    'absoluteTolerance',absoluteTolerance,'differences',difference,'exactMatches',exact);
end
