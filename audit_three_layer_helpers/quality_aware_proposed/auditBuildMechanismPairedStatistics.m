function output = auditBuildMechanismPairedStatistics(packetTable,schema)
%AUDITBUILDMECHANISMPAIREDSTATISTICS Unique paired mechanism comparisons.
comparisons=["FixedRadius3LegacyHardRejectCausal_EP","FixedRadius3Causal_EP"; ...
    "FixedRadius3LegacyNisInflationCausal_EP","FixedRadius3LegacyHardRejectCausal_EP"; ...
    "FixedRadius3LsCovOnlyCausal_EP","FixedRadius3Causal_EP"; ...
    "FixedRadius3LsCovHardRejectCausal_EP","FixedRadius3LsCovOnlyCausal_EP"; ...
    "FixedRadius3LsCovNisInflationCausal_EP","FixedRadius3LsCovHardRejectCausal_EP"; ...
    "FixedRadius3FullAdaptiveRdaCausal_EP","FixedRadius3LsCovNisInflationCausal_EP"; ...
    "QualityAwareLocalDAKalmanCausal_EP","FixedRadius3FullAdaptiveRdaCausal_EP"; ...
    "QualityWindowOnlyCausal_EP","FixedRadius3Causal_EP"; ...
    "QualityAwareLocalDAKalmanCausal_EP","FixedRadius3Causal_EP"; ...
    "FixedRadius3FullAdaptiveRdaCausal_EP","FixedRadius3Causal_EP"; ...
    "FixedRadius3LsCovNisInflationCausal_EP","FixedRadius3Causal_EP"; ...
    "BaseKalmanCausal_EP","FixedRadius3Causal_EP"];
metrics=["csiNmse","preLdpcBer","blockErrorRate","softEvmRms","worstStreamCsiNmse", ...
    "p95ReNormalizedError","p99ReNormalizedError","deepFadeCsiNmse","onlineRuntimeSeconds", ...
    "codewordPassRate","payloadGoodputMbps","evmEffectiveSinrDb"];
higherIsBetter=[false(1,9),true,true,true];payloads=unique(packetTable.payloadSymbols).';
cells=cell(numel(payloads)*size(comparisons,1)*numel(metrics),1);cursor=0;
for payload=payloads
    for comparison=1:size(comparisons,1)
        first=sortrows(packetTable(packetTable.payloadSymbols==payload&packetTable.method==comparisons(comparison,1),:),'packetIndex');
        second=sortrows(packetTable(packetTable.payloadSymbols==payload&packetTable.method==comparisons(comparison,2),:),'packetIndex');
        assert(height(first)==height(second)&&all(first.packetIndex==second.packetIndex),'Paired packet keys do not match.');
        for metricIndex=1:numel(metrics)
            delta=first.(metrics(metricIndex))-second.(metrics(metricIndex));tolerance=1e-15;
            if higherIsBetter(metricIndex),wins=nnz(delta>tolerance);losses=nnz(delta<-tolerance);else,wins=nnz(delta<-tolerance);losses=nnz(delta>tolerance);end
            cursor=cursor+1;cells{cursor}=table(payload,comparisons(comparison,1),comparisons(comparison,2),metrics(metricIndex),numel(delta),mean(delta),median(delta),min(delta),max(delta),wins,numel(delta)-wins-losses,losses,'VariableNames',schema.paired);
        end
    end
end
output=vertcat(cells{1:cursor});keys={'payloadSymbols','methodA','methodB','metric'};
assert(height(unique(output(:,keys),'rows'))==height(output),'Duplicate paired-statistics keys were generated.');
end
