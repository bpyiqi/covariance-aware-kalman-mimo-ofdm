function [C,V,B]=auditAnalyzeLlrLdpcReceiver(cfg,scenario,packet,receiver,method)
%AUDITANALYZELLRLDPCRECEIVER Truth-only diagnostics after the frozen receiver.
llr=double(receiver.llr(:));hard=llr<0;usefulLlr=llr(scenario.usefulBitMask);usefulHard=hard(scenario.usefulBitMask);
D=numel(cfg.data);N=scenario.Npayload;symbolHardGrid=false(4,2,D,N);
for n=1:N
    for d=find(scenario.validReMask(:,n)).'
        symbols=receiver.hardSymbols(:,d,n);bits=logical(qamdemod(symbols,16,'UnitAveragePower',true,'OutputType','bit'));
        symbolHardGrid(:,:,d,n)=reshape(bits,4,2);
    end
end
symbolHard=symbolHardGrid(:);symbolUseful=symbolHard(scenario.usefulBitMask);
rows=cell(3,1);scaleRows=cell(3*4,1);cursor=0;betas=[.25 .5 1 2];
for cw=1:3
    codedIndex=(cw-1)*cfg.ldpc.N+(1:cfg.ldpc.N);infoIndex=(cw-1)*(cfg.ldpc.K-32)+(1:cfg.ldpc.K-32);
    codeTrue=scenario.codedBits(codedIndex);cwLlr=usefulLlr(codedIndex);cwHard=usefulHard(codedIndex);wrong=cwHard~=codeTrue;absLlr=abs(cwLlr);
    decoded=logical(ldpcDecode(cwLlr,cfg.ldpc.dec,50,'DecisionType','hard'));payload=decoded(1:cfg.ldpc.K-32);
    crcPass=isequal(decoded(cfg.ldpc.K-31:cfg.ldpc.K),ofdm.crc32Bits(payload));postErrors=nnz(payload~=scenario.informationBits(infoIndex));
    correctAbs=absLlr(~wrong);wrongAbs=absLlr(wrong);
    rows{cw}=table(scenario.scenarioIndex,packet.targetSnrDb,method,cw,nnz(wrong),mean(wrong),crcPass,postErrors, ...
        mean(absLlr),median(absLlr),auditDeterministicPercentile(absLlr,.95),max(absLlr),0, ...
        localMean(correctAbs),localMean(wrongAbs),localMax(wrongAbs),nnz(wrongAbs>=2.5),nnz(wrongAbs>=5), ...
        nnz(wrongAbs>=10),nnz(wrongAbs>=20),nnz(isinf(wrongAbs)), ...
        nnz(cwHard~=symbolUseful(codedIndex)),NaN,NaN, ...
        'VariableNames',{'scenarioIndex','targetSnrDb','method','codewordIndex','preLdpcBitErrorCount','preLdpcBer', ...
        'decoderPass','postDecodeBitErrorCount','meanAbsLlr','medianAbsLlr','p95AbsLlr','maxAbsLlr','llrClipFraction', ...
        'correctBitMeanAbsLlr','wrongBitMeanAbsLlr','wrongBitMaxAbsLlr','wrongBitHighConfidenceCount2p5', ...
        'wrongBitHighConfidenceCount5','wrongBitHighConfidenceCount10','wrongBitHighConfidenceCount20', ...
        'wrongBitSaturatedCount','hardDecisionMismatchCount','decoderIterationCount','finalSyndromeWeight'});
    for beta=betas
        cursor=cursor+1;scaled=beta*cwLlr;d=logical(ldpcDecode(scaled,cfg.ldpc.dec,50,'DecisionType','hard'));p=d(1:cfg.ldpc.K-32);
        ok=isequal(d(cfg.ldpc.K-31:cfg.ldpc.K),ofdm.crc32Bits(p));errors=nnz(p~=scenario.informationBits(infoIndex));
        scaleRows{cursor}=table(method,scenario.scenarioIndex,packet.targetSnrDb,cw,beta,ok,errors, ...
            'VariableNames',{'method','scenarioIndex','targetSnrDb','codewordIndex','beta','decoderPass','postDecodeBitErrorCount'});
    end
end
C=vertcat(rows{:});B=vertcat(scaleRows{1:cursor});
pv=double(receiver.posteriorVariance(:));pv=pv(isfinite(pv));absUseful=abs(usefulLlr);
V=table(method,scenario.scenarioIndex,packet.targetSnrDb,packet.realizedSnrDb,cfg.noiseVar,cfg.noiseVar,cfg.noiseVar/2, ...
    cfg.noiseVar,NaN,mean(pv),min(pv),max(pv),any(pv<=1e-12),1e-12,mean(absUseful),mean(absUseful),false, ...
    'VariableNames',{'method','scenarioIndex','targetSnrDb','realizedSnrDb','channelNoiseVariance', ...
    'complexNoiseVariance','perRealDimensionNoiseVariance','variancePassedToEP','varianceUsedForQamLlr', ...
    'meanPosteriorSymbolVariance','minimumPosteriorSymbolVariance','maximumPosteriorSymbolVariance', ...
    'anyVarianceFloor','varianceFloorValue','llrScaleBeforeClip','llrScaleAfterClip','explicitDecoderLlrClip'});
end
