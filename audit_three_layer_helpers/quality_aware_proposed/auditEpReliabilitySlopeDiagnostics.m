function diagnostics = auditEpReliabilitySlopeDiagnostics(cfg,source)
%AUDITEPRELIABILITYSLOPEDIAGNOSTICS
% Diagnostic-only per-method logistic calibration fits.

samplePerRecord = 10000;
M = numel(cfg.methods);

% 从正式输入确定scenario数量，避免硬编码12
scenarioCount = numel(source.chunkPaths);

% 从第一个chunk确定每个方法对应的SNR记录数
probe = load(source.chunkPaths(1),'chunk');
recordCount = numel(probe.chunk.records);

assert(mod(recordCount,M) == 0, ...
    ['chunk记录数量%d不能被方法数量%d整除，' ...
     '无法确定每个方法的SNR记录数。'], ...
    recordCount,M);

snrCount = recordCount / M;

samples = cell(M,scenarioCount,snrCount);
sampleCount = zeros(M,scenarioCount);

for s = 1:scenarioCount
    loaded = load(source.chunkPaths(s),'chunk');
    truth = logical(loaded.chunk.codedBits(:));

    for r = 1:numel(loaded.chunk.records)
        rec = loaded.chunk.records{r};

        m = find(cfg.methods == string(rec.method),1);

        assert(~isempty(m), ...
            '未识别方法：%s。',string(rec.method));

        llr = double(rec.rawUsefulLlr(:));

        assert(numel(llr) == numel(truth), ...
            ['scenario=%d，method=%s的LLR长度%d' ...
             '与coded bits长度%d不一致。'], ...
            s,string(rec.method),numel(llr),numel(truth));

        takeCount = min(samplePerRecord,numel(llr));
        take = round(linspace(1,numel(llr),takeCount));

        sampleCount(m,s) = sampleCount(m,s) + 1;

        assert(sampleCount(m,s) <= snrCount, ...
            'scenario=%d，method=%s的记录数量超过预期%d。', ...
            s,string(rec.method),snrCount);

        % y=1表示coded bit 0，与LLR>0表示bit 0一致
        samples{m,s,sampleCount(m,s)} = ...
            [llr(take),double(~truth(take))];
    end
end

assert(all(sampleCount == snrCount,'all'), ...
    '至少一个method-scenario组合的SNR记录数不完整。');

rows = cell(M,1);

state = rng;
cleanup = onCleanup(@()rng(state)); 
rng(cfg.calibrationBootstrapSeed,'twister');

for m = 1:M
    % 当前方法全部scenario和SNR数据
    methodParts = reshape(samples(m,:,:),[],1);
    allData = vertcat(methodParts{:});

    fit = reshape(localFit(allData),1,[]);
    fitWidth = numel(fit);

    assert(fitWidth == 4, ...
        'localFit预期返回4个值，实际返回%d个。',fitWidth);

    bootstrap = nan( ...
        cfg.calibrationBootstrapCount,fitWidth);

    for b = 1:cfg.calibrationBootstrapCount
        % scenario-level bootstrap：
        % 抽中一个scenario时保留其全部SNR数据
        selected = randi( ...
            scenarioCount,scenarioCount,1);

        bootstrapData = ...
            localScenarioSample(samples,m,selected);

        fitBootstrap = reshape( ...
            localFit(bootstrapData),1,[]);

        assert(numel(fitBootstrap) == fitWidth, ...
            ['bootstrap第%d次localFit宽度异常：' ...
             '预期%d，实际%d。'], ...
            b,fitWidth,numel(fitBootstrap));

        bootstrap(b,:) = fitBootstrap;
    end

    slopeCiLower = auditDeterministicPercentile( ...
        bootstrap(:,1),0.025);

    slopeCiUpper = auditDeterministicPercentile( ...
        bootstrap(:,1),0.975);

    interceptCiLower = auditDeterministicPercentile( ...
        bootstrap(:,2),0.025);

    interceptCiUpper = auditDeterministicPercentile( ...
        bootstrap(:,2),0.975);

    interceptImprovesNll = fit(4) < 0.99*fit(3);

    interceptRequiredDiagnostic = ...
        ~(interceptCiLower <= 0 && interceptCiUpper >= 0);

    rows{m} = table( ...
        cfg.methods(m), ...
        fit(1), ...
        fit(2), ...
        slopeCiLower, ...
        slopeCiUpper, ...
        interceptCiLower, ...
        interceptCiUpper, ...
        fit(3), ...
        fit(4), ...
        interceptImprovesNll, ...
        interceptRequiredDiagnostic, ...
        size(allData,1), ...
        'VariableNames',{ ...
            'method', ...
            'slopeA', ...
            'interceptC', ...
            'slopeCiLower95', ...
            'slopeCiUpper95', ...
            'interceptCiLower95', ...
            'interceptCiUpper95', ...
            'scaleOnlyNll', ...
            'slopeInterceptNll', ...
            'interceptImprovesNll', ...
            'interceptRequiredDiagnostic', ...
            'sampleBitCount'});
end

diagnostics = vertcat(rows{:});

end


function data = localScenarioSample(samples,method,selected)

snrCount = size(samples,3);
parts = cell(numel(selected)*snrCount,1);
cursor = 0;

for i = 1:numel(selected)
    for snr = 1:snrCount
        cursor = cursor + 1;

        part = samples{method,selected(i),snr};

        assert(~isempty(part), ...
            ['bootstrap抽样遇到空数据：' ...
             'method=%d，scenario=%d，snrIndex=%d。'], ...
            method,selected(i),snr);

        parts{cursor} = part;
    end
end

data = vertcat(parts{:});

end


function values = localFit(data)

assert(size(data,2) == 2 && ~isempty(data), ...
    'localFit输入必须为非空N×2矩阵。');

L = data(:,1);
y = data(:,2);

objective = @(x) mean( ...
    auditStableSoftplus(x(1)*L + x(2)) ...
    - y.*(x(1)*L + x(2)));

options = optimset( ...
    'Display','off', ...
    'MaxIter',100, ...
    'TolX',1e-7);

% 只拟合尺度，intercept固定为0
scale = fminsearch( ...
    @(a)objective([a 0]),1,options);

% 同时拟合尺度和intercept
both = fminsearch( ...
    objective,[scale 0],options);

values = [ ...
    both(1), ...
    both(2), ...
    objective([scale 0]), ...
    objective(both)];

assert(all(isfinite(values)), ...
    'localFit产生NaN或Inf。');

end