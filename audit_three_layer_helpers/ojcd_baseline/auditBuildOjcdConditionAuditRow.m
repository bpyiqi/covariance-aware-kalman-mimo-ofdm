function tableOut = auditBuildOjcdConditionAuditRow(result, payloadSymbols, packetIndex)
%AUDITBUILDOJCDCONDITIONAUDITROW Build one packet's OJCD condition row.
names={'conditionSampleCount','conditionMean','conditionMedian','conditionP90', ...
    'conditionP95','conditionP99','conditionMaximum','rcondMinimum','rcondP01', ...
    'minEigenvalueMinimum','minimumCholeskyPivot','regularizationCount', ...
    'regularizationRate','maximumRegularizationLoading','solverFailureCount', ...
    'nonFiniteMatrixCount','nonFiniteSolutionCount','nonFiniteConditionCount', ...
    'nonFiniteRcondCount','nonFiniteEigenvalueCount','nonFiniteCholeskyPivotCount'};
assert(isstruct(result)&&isscalar(result),'OJCD condition result must be a scalar structure.');
missing=setdiff(names,fieldnames(result));
assert(isempty(missing),'OJCD condition result is missing fields: %s',strjoin(missing,','));
values=cellfun(@(name)result.(name),names,'UniformOutput',false);
assert(all(cellfun(@(value)isnumeric(value)&&isscalar(value),values)), ...
    'OJCD condition audit fields must be numeric scalars.');
tableOut=cell2table([{payloadSymbols,packetIndex} values], ...
    'VariableNames',[{'payloadSymbols','packetIndex'} names]);
assert(height(tableOut)==1,'OJCD condition audit must contain exactly one row per packet.');
end
