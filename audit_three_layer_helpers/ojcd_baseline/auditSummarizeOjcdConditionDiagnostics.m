function summary = auditSummarizeOjcdConditionDiagnostics(diagnostics)
%AUDITSUMMARIZEOJCDCONDITIONDIAGNOSTICS Summarize scalar solve diagnostics.
% Input fields are vectors with one element per valid OJCD matrix solve.
condition=diagnostics.conditionNumber(:);rcondValues=diagnostics.reciprocalConditionNumber(:);
eigenvalues=diagnostics.minEigenvalueHermitianPart(:);pivots=diagnostics.minimumCholeskyPivot(:);
triggered=logical(diagnostics.regularizationTriggered(:));loading=diagnostics.regularizationLoading(:);
sampleCount=numel(condition);finiteCondition=condition(isfinite(condition));finiteRcond=rcondValues(isfinite(rcondValues));
finiteEigen=eigenvalues(isfinite(eigenvalues));finitePivot=pivots(isfinite(pivots));
summary=struct('conditionSampleCount',sampleCount,'conditionMean',meanOrNaN(finiteCondition), ...
    'conditionMedian',quantileLinear(finiteCondition,.5),'conditionP90',quantileLinear(finiteCondition,.90), ...
    'conditionP95',quantileLinear(finiteCondition,.95),'conditionP99',quantileLinear(finiteCondition,.99), ...
    'conditionMaximum',maxOrNaN(finiteCondition),'rcondMinimum',minOrNaN(finiteRcond), ...
    'rcondP01',quantileLinear(finiteRcond,.01),'minEigenvalueMinimum',minOrNaN(finiteEigen), ...
    'minimumCholeskyPivot',minOrNaN(finitePivot),'regularizationCount',nnz(triggered), ...
    'regularizationRate',nnz(triggered)/max(sampleCount,1), ...
    'maximumRegularizationLoading',max([0;loading(isfinite(loading))]), ...
    'solverFailureCount',nnz(diagnostics.solverFailure), ...
    'nonFiniteMatrixCount',nnz(diagnostics.nonFiniteMatrix), ...
    'nonFiniteSolutionCount',nnz(diagnostics.nonFiniteSolution), ...
    'nonFiniteConditionCount',nnz(~isfinite(condition)), ...
    'nonFiniteRcondCount',nnz(~isfinite(rcondValues)), ...
    'nonFiniteEigenvalueCount',nnz(~isfinite(eigenvalues)), ...
    'nonFiniteCholeskyPivotCount',nnz(~isfinite(pivots)));
end
function value=quantileLinear(values,p)
values=sort(values(:));n=numel(values);if n==0,value=NaN;return;end
position=1+(n-1)*p;lo=floor(position);hi=ceil(position);weight=position-lo;
value=(1-weight)*values(lo)+weight*values(hi);
end
function value=meanOrNaN(x),if isempty(x),value=NaN;else,value=mean(x);end,end
function value=minOrNaN(x),if isempty(x),value=NaN;else,value=min(x);end,end
function value=maxOrNaN(x),if isempty(x),value=NaN;else,value=max(x);end,end
